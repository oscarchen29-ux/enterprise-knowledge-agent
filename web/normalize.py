"""把台灣口語與常見錯字整理成模型讀得懂的問句。

為什麼需要:模型是中國語料訓練的,看不懂台灣人怎麼打字。實測「阿大一呢」被讀成
人名,模型連問三次「請問您要問的是阿大一的必修課程嗎?」——「阿」在台灣口語是
句首發語詞,等於「那」。這不是檢索或推理的問題,是在地用語的問題,而且是輸入端的
問題(輸出端的簡體字已經有 OpenCC 在處理)。

三條原則:

1. **只改幾乎不會有歧義的。** 「在/再」「的/得/地」這種要看語境才判得出來的一律不碰,
   猜錯比不改更糟。

2. **只在詞界安全的位置改。** 「阿」只在句首、而且後面接得上內容時才換掉,
   否則「阿拉伯數字」會被改壞。

3. **混合檢索本身就吃得下一部分噪音。** bge-m3 的向量比對對錯字比 BM25 容忍得多,
   所以這裡只處理「會讓模型誤解語意」的部分,不需要做成完整的拼字檢查。
"""

import re

# 句首發語詞。台灣口語很常用,但對模型只是雜訊,甚至會被當成名詞的一部分。
# 「阿/啊」語意接近「那」,保留成「那」比刪掉好 —— 它標示了這是接續提問。
_SENTENCE_HEAD = [
    (re.compile(r"^[阿啊][\s,,]*(?=[那這大碩博一二三四五六七八九十研學我要想有能可])"), "那"),
    (re.compile(r"^[欸誒耶][\s,,]*"), ""),
    (re.compile(r"^[齁厚吼][\s,,]*"), ""),
    (re.compile(r"^(那個|就是說|所以說)[\s,,]*"), ""),
]

# 口語詞彙。左邊是台灣人實際會打的,右邊是模型讀得懂的。
_COLLOQUIAL = [
    (r"蝦米|瞎密|殺小", "什麼"),
    (r"(?<![一-鿿])啥(?![麼])", "什麼"),
    (r"(?<![一-鿿])醬(?![油汁料])", "這樣"),
    (r"這樣子", "這樣"),
    (r"幹嘛|干嘛", "做什麼"),
    (r"怎樣辦|怎辦", "怎麼辦"),
    (r"多久拉|多久勒|多久咧", "多久"),
    (r"[咧勒](?=[??]|$)", "呢"),
    (r"[唷喔喲](?=[??]|$)", ""),
    (r"欸不是", ""),
    # 剝除疊用的發語詞後可能留下「那那個」,收乾淨
    (r"^那那個?", "那"),
]

# 注音簡寫。年輕人打字常用,模型完全讀不懂。
_BOPOMOFO = [
    (r"ㄉ", "的"), (r"ㄅ", "不"), (r"ㄇ", "嗎"), (r"ㄋ", "呢"),
    (r"ㄏㄏ|ㄎㄎ", ""), (r"ㄍ", "個"),
]

# 這個領域特有的錯字。都是同音或形近,而且在校務語境下不會有別的意思。
_DOMAIN_TYPOS = [
    (r"學份", "學分"),
    (r"必休(?=課|科|的|有|是|$)", "必修"),
    (r"選休(?=課|科|的|有|是|$)", "選修"),
    (r"抵勉|底免", "抵免"),
    (r"畢業門坎", "畢業門檻"),
    (r"退宿費", "退宿"),
    (r"專提", "專題"),
    (r"論文口式", "論文口試"),
    (r"獎學今", "獎學金"),
    (r"研究生宿舍", "研究生學生宿舍"),
    (r"因該", "應該"),
    (r"在(?=麼辦|樣辦)", "怎"),
    (r"遺下|一夏", "一下"),
]

_RULES = [(re.compile(p), r) for p, r in _COLLOQUIAL + _BOPOMOFO + _DOMAIN_TYPOS]


def normalize(text: str) -> str:
    """回傳整理過的問句。改不動的部分原樣保留。"""
    out = (text or "").strip()
    if not out:
        return out
    # 發語詞會疊著用(「欸阿那個⋯」),所以要重複剝除;上限三輪,避免規則互相
    # 觸發而無限迴圈。
    for _ in range(3):
        before = out
        for pattern, replacement in _SENTENCE_HEAD:
            new = pattern.sub(replacement, out, count=1)
            if new != out:
                out = new.strip()
                break
        if out == before:
            break
    for pattern, replacement in _RULES:
        out = pattern.sub(replacement, out)
    return out.strip()


if __name__ == "__main__":
    import sys, io
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    cases = [
        "阿大一呢", "欸請問休學要幹嘛", "蝦米是抵免", "醬算幾學份",
        "那個我想問一下宿舍", "必休有哪些咧", "ㄅ知道ㄉ話要問誰",
        "因該要修幾學分", "阿拉伯數字怎麼寫", "大三必修有哪些",
        "醬油可以帶進宿舍嗎", "專提要幾個人",
    ]
    for c in cases:
        n = normalize(c)
        print(f"  {c!r:<26} -> {n!r}{'' if n != c else '   (未變動)'}")
