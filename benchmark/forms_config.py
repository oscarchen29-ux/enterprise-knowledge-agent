def _eng_verdict_ok(got, case):
    """標註的「符合」清單:空 -> 應判不符合;['不確定'] -> 應判不確定;有項目 -> 符合或部分符合。"""
    got = (got or "").strip()
    expected = case["verdict"].get("符合", [])
    if expected == ["不確定"]:
        return "不確定" in got
    if not expected:
        return got.startswith("不符合")
    return got.startswith("符合") or got.startswith("部分符合")


